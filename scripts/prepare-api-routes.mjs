import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const hash=code=>crypto.createHash('sha256').update(code.replace(/\r\n/g,'\n')).digest('hex');
async function files(directory){const result=[];for(const entry of await fs.readdir(directory,{withFileTypes:true}).catch(error=>{if(error.code==='ENOENT')return [];throw error;})){const file=path.join(directory,entry.name);if(entry.isDirectory())result.push(...await files(file));else if(entry.isFile())result.push(file);}return result;}
export async function prepareApiRoutes(projectRoot=root){
 const manifest=JSON.parse(await fs.readFile(path.join(projectRoot,'scripts/api-routes.json'),'utf8'));
 const apiRoot=path.join(projectRoot,'app/api'),legacy=[];
 for(const file of await files(apiRoot)){
  const rel=path.relative(apiRoot,file).split(path.sep).join('/');
  if(rel==='[...path]/route.js'||!/^route\.(?:[cm]?js|jsx|tsx?)$/.test(path.basename(file)))continue;
  const entry=manifest.find(route=>route.file===rel),code=await fs.readFile(file,'utf8');
  if(!entry||hash(code)!==entry.legacySha256)throw new Error(`Custom or unknown API entry point found: app/api/${rel}. Move its changes into app/_api and update scripts/api-routes.json before building. No legacy files were removed.`);
  legacy.push({file,rel});
 }
 for(const entry of manifest)await fs.access(path.join(projectRoot,'app/_api',entry.file));
 // GitHub's Upload files action retains old files. Preserve recognised v9 copies outside the routing tree.
 for(const entry of legacy){const destination=path.join(projectRoot,'app/_api-migration-backup',path.dirname(entry.rel),crypto.randomUUID()+'-route.js');await fs.mkdir(path.dirname(destination),{recursive:true});await fs.rename(entry.file,destination);}
 const imports=manifest.map((entry,i)=>`import * as handler${i} from './${entry.file}';`).join('\n');
 const registry='// Generated by scripts/prepare-api-routes.mjs. Keep public URLs in scripts/api-routes.json.\n'+imports+'\n\nexport const routes=[\n'+manifest.map((entry,i)=>`  {path:${JSON.stringify(entry.path)},handlers:handler${i}},`).join('\n')+'\n];\n';
 const registryPath=path.join(projectRoot,'app/_api/registry.js');
 if(await fs.readFile(registryPath,'utf8').catch(()=>null)!==registry)await fs.writeFile(registryPath,registry);
 return {apiHandlers:manifest.length,apiEntrypoints:1,legacyFilesPreserved:legacy.length};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(JSON.stringify(await prepareApiRoutes()));
